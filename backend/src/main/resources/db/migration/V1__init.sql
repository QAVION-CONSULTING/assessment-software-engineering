-- ============================================================
-- Timetracker — V1 initial schema
-- PostgreSQL 18
--
-- Money and durations are stored as integers in minor units:
--  - euro cents for money (960000 = 9600.00 EUR)
--  - minutes for durations (450 = 7.5 h)
-- ============================================================

-- ------------------------------------------------------------
-- Projects
-- One row per project with its time budget (minutes), cost
-- budget (euro cents) and hourly rate (euro cents per hour).
-- ------------------------------------------------------------
CREATE TABLE projects (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL,
    description         VARCHAR(500),           -- optional
    time_budget_minutes INTEGER      NOT NULL CHECK (time_budget_minutes > 0),
    cost_budget_cents   BIGINT       NOT NULL CHECK (cost_budget_cents > 0),
    hourly_rate_cents   INTEGER      NOT NULL CHECK (hourly_rate_cents > 0),
    version             BIGINT       NOT NULL   -- optimistic locking (@Version)
);

-- ------------------------------------------------------------
-- Time entries
-- Working time per day, linked to a project.
-- ------------------------------------------------------------
CREATE TABLE time_entries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date             DATE    NOT NULL,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0 AND duration_minutes <= 1440),
    description      VARCHAR(500),           -- optional
    version          BIGINT  NOT NULL,       -- optimistic locking (@Version)
    project_id       BIGINT  NOT NULL,

    CONSTRAINT fk_time_entries_project
        FOREIGN KEY (project_id)
        REFERENCES projects (id)
        ON DELETE CASCADE    -- deleting a project removes its time entries
);

CREATE INDEX idx_time_entries_date       ON time_entries (date);
CREATE INDEX idx_time_entries_project_id ON time_entries (project_id);
